/**
 * Planning: turns a free-text request into a draft delivery spec for a human
 * to review. Planning never implements, never runs checks and never delivers.
 *
 *   ade plan "<request>"   -> <dir>/draft.json + <dir>/proposed-tests/...   (unapproved)
 *   ade approve <draft>    -> <dir>/spec.json                               (explicit human step)
 *   ade deliver <spec>     -> refuses drafts; runs only approved specs
 *
 * Everything the model proposes, especially checks and test files, stays
 * marked as unapproved until a person runs `ade approve` after reviewing it.
 */
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, normalize, resolve, sep } from 'node:path';
import { DomainError } from '../domain/errors.js';
import { rejectUnknownKeys, requireNonEmptyString, requireObject, stringList } from '../domain/validation.js';
import { DRAFT_KIND, prepareDelivery } from '../controller/spec.js';
import { sha256File } from '../controller/integrity.js';

export const MAX_REQUEST_LENGTH = 10_000;
const PROPOSED_TESTS_DIR = 'proposed-tests';
const MODEL_FIELDS = ['summary', 'assumptions', 'openQuestions', 'requirements', 'tasks', 'checks', 'testFiles'];
const APPROVAL_NOTE =
  'DRAFT. Generated by a model and NOT approved. Review every requirement, check command and proposed test file, ' +
  'then run `ade approve` on this file. Proposed checks are never executed before approval.';

/** Planning failed: bad request, failed agent session, unusable model output, or an unsafe write. */
export class PlanningError extends DomainError {
  constructor(message, { code = 'PLANNING_ERROR', details } = {}) {
    super(message, { code, details });
  }
}

export function validateRequest(request) {
  if (typeof request !== 'string' || request.trim() === '') {
    throw new PlanningError('The request must be a non-empty description of the application.', { code: 'INVALID_REQUEST' });
  }
  if (request.length > MAX_REQUEST_LENGTH) {
    throw new PlanningError(`The request is longer than ${MAX_REQUEST_LENGTH} characters.`, { code: 'INVALID_REQUEST' });
  }
  return request.trim();
}

export function buildPlanningPrompt(request) {
  return `You are the planning step of ADE, a system that delivers applications and independently verifies them.
Turn the request below into a draft delivery specification for a human to review. You cannot use tools.

Rules:
- Only include requirements the request states or clearly implies. Do not invent features.
- Where the request is ambiguous, record the choice you made in "assumptions". If a decision
  materially changes what gets built and you cannot reasonably assume it, add a focused question
  to "openQuestions" instead.
- Requirement ids are FR1, FR2, ... Every requirement has at least one testable acceptance criterion
  and lists the ids of the checks that verify it in "checkIds".
- Tasks have ids T1, T2, ...; use "dependsOn" only where one task genuinely needs another first.
- The application is built with Node.js and no third-party dependencies unless the request requires them.
- Each check runs one program with arguments (no shell), from the application directory, e.g.
  { "command": "node", "args": ["--test", "acceptance/fr1.test.mjs"] }. Prefer one check per requirement.
- Provide the acceptance test file for every check in "testFiles". Tests are ES modules named
  acceptance/<name>.test.mjs using node:test and node:assert/strict, importing the application by
  relative path. Name in the task descriptions the exact files and exports the tests import.

Respond with ONLY one JSON object, no prose and no code fences, of this shape:
{
  "summary": "one-paragraph description of the application",
  "assumptions": ["..."],
  "openQuestions": ["..."],
  "requirements": [{ "id": "FR1", "description": "...", "acceptanceCriteria": ["..."], "checkIds": ["acceptance-fr1"] }],
  "tasks": [{ "id": "T1", "title": "...", "description": "...", "dependsOn": [], "requirementIds": ["FR1"] }],
  "checks": [{ "id": "acceptance-fr1", "description": "...", "command": "node", "args": ["--test", "acceptance/fr1.test.mjs"], "timeoutMs": 30000, "requirementIds": ["FR1"] }],
  "testFiles": [{ "path": "acceptance/fr1.test.mjs", "content": "..." }]
}

Request:
"""
${request}
"""`;
}

/** Extracts the JSON object from the model's reply. Tolerates a code fence, nothing else. */
export function parseModelOutput(text) {
  if (typeof text !== 'string' || text.trim() === '') {
    throw new PlanningError('The planner returned no output.', { code: 'MALFORMED_OUTPUT' });
  }
  const fenced = /^```(?:json)?\s*\n([\s\S]*?)\n```\s*$/.exec(text.trim());
  const body = fenced ? fenced[1] : text.trim();
  try {
    const value = JSON.parse(body);
    requireObject(value, 'Planner output');
    return value;
  } catch (error) {
    throw new PlanningError(`The planner output is not a JSON object: ${error.message}`, {
      code: 'MALFORMED_OUTPUT',
      details: { excerpt: body.slice(0, 500) },
    });
  }
}

/**
 * Validates the model's plan and turns it into a draft. The would-be spec is
 * checked with the same `prepareDelivery` that `ade deliver` uses, so a draft
 * that saves successfully has a valid schema and complete traceability.
 */
export function createDraft(plan, { request, generator, now = new Date() }) {
  try {
    rejectUnknownKeys(plan, MODEL_FIELDS, 'Planner output');
    const testFiles = (Array.isArray(plan.testFiles) ? plan.testFiles : []).map(testFile);
    const draft = {
      kind: DRAFT_KIND,
      version: 1,
      approval: { status: 'draft', note: APPROVAL_NOTE },
      generatedAt: new Date(now).toISOString(),
      generator,
      request,
      summary: requireNonEmptyString(plan.summary, 'summary', 'Planner output'),
      assumptions: stringList(plan.assumptions, 'assumptions', 'Planner output'),
      openQuestions: stringList(plan.openQuestions, 'openQuestions', 'Planner output'),
      requirements: plan.requirements,
      tasks: plan.tasks,
      proposedChecks: plan.checks,
      proposedTestFiles: testFiles.map(({ path, sha256 }) => ({ path, file: `${PROPOSED_TESTS_DIR}/${path}`, sha256 })),
    };
    assertTestable(draft);
    prepareDelivery(specFromDraft(draft), process.cwd());
    return { draft, testFiles };
  } catch (error) {
    if (error instanceof PlanningError) throw error;
    throw new PlanningError(`The generated plan is invalid: ${error.message}`, {
      code: 'INVALID_PLAN',
      details: { cause: error.code },
    });
  }
}

/**
 * The delivery spec a draft would become once approved. `hashes` maps each
 * proposed test path to the hash being approved; by default the hash of the
 * generated content is used (only for validating the draft's shape).
 */
export function specFromDraft(draft, hashes = {}) {
  return {
    request: draft.request,
    workspace: './workspace',
    maxRepairAttempts: 2,
    requirements: draft.requirements,
    tasks: draft.tasks,
    checks: draft.proposedChecks,
    protectedFiles: draft.proposedTestFiles.map((f) => ({ from: f.file, to: f.path, sha256: hashes[f.path] ?? f.sha256 })),
  };
}

/**
 * Writes draft.json and the proposed test files into `dir`. Refuses to
 * overwrite anything: an existing draft or test file is an error.
 */
export async function writeDraft(dir, { draft, testFiles }) {
  const draftPath = join(dir, 'draft.json');
  await mkdir(dir, { recursive: true });
  await writeNew(draftPath, `${JSON.stringify(draft, null, 2)}\n`);
  for (const file of testFiles) {
    const target = join(dir, PROPOSED_TESTS_DIR, file.path);
    await mkdir(dirname(target), { recursive: true });
    await writeNew(target, file.content);
  }
  return draftPath;
}

/**
 * Runs the planner end to end: request -> agent (no tools) -> validated draft on disk.
 * @param {string} request
 * @param {object} options
 * @param {{ name: string, plan: Function }} options.agent
 * @param {string} options.outDir
 */
export async function planApplication(request, { agent, outDir, now }) {
  const text = validateRequest(request);
  // The planner runs in an empty scratch directory: it has no tools, and there is nothing to see.
  const scratch = await mkdtemp(join(tmpdir(), 'ade-plan-'));
  let session;
  try {
    session = await agent.plan({ workspace: scratch, prompt: buildPlanningPrompt(text) });
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
  if (!session.ok) {
    throw new PlanningError(`The planning session failed: ${String(session.text).slice(0, 300)}`, { code: 'AGENT_FAILED' });
  }
  const prepared = createDraft(parseModelOutput(session.text), { request: text, generator: agent.name, now });
  const draftPath = await writeDraft(outDir, prepared);
  return { draftPath, draft: prepared.draft };
}

/**
 * The explicit human approval step. Re-validates the (possibly hand-edited)
 * draft, hashes the exact test files on disk being approved (edits made during
 * review included) and writes spec.json with those hashes. Delivery refuses to
 * verify against any file that no longer matches. Refuses while open questions
 * remain unless `allowOpenQuestions` is set.
 */
export async function approveDraft(draftPath, { allowOpenQuestions = false, now = new Date() } = {}) {
  let draft;
  try {
    draft = JSON.parse(await readFile(draftPath, 'utf8'));
  } catch (error) {
    throw new PlanningError(`Cannot read draft ${draftPath}: ${error.message}`, { code: 'INVALID_DRAFT' });
  }
  if (draft?.kind !== DRAFT_KIND) {
    throw new PlanningError(`${draftPath} is not an ADE draft spec.`, { code: 'INVALID_DRAFT' });
  }
  if (draft.openQuestions?.length && !allowOpenQuestions) {
    throw new PlanningError(
      `The draft has ${draft.openQuestions.length} open question(s). Resolve them (edit the draft and clear ` +
        '"openQuestions") or pass --allow-open-questions.',
      { code: 'OPEN_QUESTIONS', details: { openQuestions: draft.openQuestions } },
    );
  }
  const dir = dirname(resolve(draftPath));
  const hashes = {};
  const edited = [];
  for (const file of draft.proposedTestFiles ?? []) {
    hashes[file.path] = await sha256File(join(dir, file.file)).catch(() => {
      throw new PlanningError(`Proposed test file ${file.file} is missing.`, { code: 'INVALID_DRAFT' });
    });
    if (hashes[file.path] !== file.sha256) edited.push(file.path);
  }
  const spec = specFromDraft(draft, hashes);
  try {
    prepareDelivery(spec, dir);
  } catch (error) {
    throw new PlanningError(`The draft is not a valid spec: ${error.message}`, { code: 'INVALID_DRAFT' });
  }
  const specPath = join(dir, 'spec.json');
  await writeNew(specPath, `${JSON.stringify(spec, null, 2)}\n`);
  return { specPath, spec, editedTests: edited, approvedAt: new Date(now).toISOString() };
}

function assertTestable(draft) {
  for (const req of draft.requirements ?? []) {
    if (!req?.acceptanceCriteria?.length || !req?.checkIds?.length) {
      throw new PlanningError(`Requirement "${req?.id}" needs acceptance criteria and at least one check.`, {
        code: 'INVALID_PLAN',
        details: { requirementId: req?.id },
      });
    }
  }
  if (!draft.requirements?.length || !draft.tasks?.length) {
    throw new PlanningError('The plan needs at least one requirement and one task.', { code: 'INVALID_PLAN' });
  }
  const paths = draft.proposedTestFiles.map((f) => f.path);
  if (new Set(paths).size !== paths.length) {
    throw new PlanningError('The plan proposes the same test file twice.', { code: 'INVALID_PLAN' });
  }
}

function testFile(entry, index) {
  requireObject(entry, `testFiles[${index}]`);
  rejectUnknownKeys(entry, ['path', 'content'], 'Test file');
  const path = requireNonEmptyString(entry.path, 'path', 'Test file');
  const normalized = normalize(path);
  if (isAbsolute(path) || normalized === '..' || normalized.startsWith(`..${sep}`)) {
    throw new PlanningError(`Test file path "${path}" must be relative and stay inside the application.`, {
      code: 'UNSAFE_PATH',
      details: { path },
    });
  }
  if (typeof entry.content !== 'string' || entry.content.trim() === '') {
    throw new PlanningError(`Test file "${path}" has no content.`, { code: 'INVALID_PLAN' });
  }
  const sha256 = createHash('sha256').update(entry.content).digest('hex');
  return { path: normalized, content: entry.content, sha256 };
}

async function writeNew(path, content) {
  try {
    await writeFile(path, content, { flag: 'wx' });
  } catch (error) {
    if (error.code === 'EEXIST') {
      throw new PlanningError(`Refusing to overwrite existing file ${path}.`, { code: 'FILE_EXISTS', details: { path } });
    }
    throw error;
  }
}
